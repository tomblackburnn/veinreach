/**
 * Crafting recipes. `station` is a crafting station tag provided by a nearby
 * tile (see TileDef.station); omit it for hand-crafting. `requires` gates a
 * recipe behind a world progression flag.
 */
export interface RecipeDef {
  out: string;
  count?: number;
  ing: [string, number][];
  station?: string;
  requires?: string;
}

